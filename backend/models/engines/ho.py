FORWARD_HO_MAP = {k: v for k, v in HO_MAPPINGS}
_sorted_ho = sorted(FORWARD_HO_MAP.keys(), key=len, reverse=True)
_alts_ho = "|".join(re.escape(k) for k in _sorted_ho)
PUNCT = r"[^\s.,?!।॥\(\)\[\]\'\"]"
_RE_FORWARD_HO = re.compile(rf"(?<!{PUNCT})(?:{_alts_ho})(?!{PUNCT})")

REVERSE_HO_MAP = {v: k for k, v in reversed(HO_MAPPINGS)}
_sorted_rev_ho = sorted(REVERSE_HO_MAP.keys(), key=len, reverse=True)
_alts_rev_ho = "|".join(re.escape(k) for k in _sorted_rev_ho)
_RE_REVERSE_HO = re.compile(rf"(?<!{PUNCT})(?:{_alts_rev_ho})(?!{PUNCT})")


class HoEngine(BaseTranslationEngine):
    @property
    def name(self) -> str:
        return "boli/ho-linguistic-transfer"

    @property
    def mode(self) -> str:
        return "linguistic_transfer"

    def supports(self, source: str, target: str) -> bool:
        s = source.lower().split("_")[0]
        t = target.lower().split("_")[0]
        return (s == "hin" and t == "hoc") or (s == "hoc" and t == "hin")

    def translate_sentence(self, sent: str, source: str, target: str) -> str:
        s = source.lower().split("_")[0]
        t = target.lower().split("_")[0]
        if s == "hin" and t == "hoc":
            return _RE_FORWARD_HO.sub(lambda m: FORWARD_HO_MAP[m.group(0)], sent)
        elif s == "hoc" and t == "hin":
            return _RE_REVERSE_HO.sub(lambda m: REVERSE_HO_MAP[m.group(0)], sent)
        return sent

    def translate_sentences(self, sentences: List[str], source: str, target: str) -> List[str]:
        return [self.translate_sentence(s, source, target) for s in sentences]
