# Build pre-compiled single-pass replacement regexes to avoid cascading substitutions
FORWARD_MAP = {k: v for k, v in SADRI_MAPPINGS}
_sorted_fwd = sorted(FORWARD_MAP.keys(), key=len, reverse=True)
_alts_fwd = "|".join(re.escape(k) for k in _sorted_fwd)
_RE_FORWARD = re.compile(
    rf"(?<![^\s.,?!।॥\(\)\[\]\'\"])(?:{_alts_fwd})(?![^\s.,?!।॥\(\)\[\]\'\"])"
)

REVERSE_MAP = {v: k for k, v in reversed(SADRI_MAPPINGS)}
_sorted_rev = sorted(REVERSE_MAP.keys(), key=len, reverse=True)
_alts_rev = "|".join(re.escape(k) for k in _sorted_rev)
_RE_REVERSE = re.compile(
    rf"(?<![^\s.,?!।॥\(\)\[\]\'\"])(?:{_alts_rev})(?![^\s.,?!।॥\(\)\[\]\'\"])"
)


class SadriEngine(BaseTranslationEngine):
    @property
    def name(self) -> str:
        return "boli/sadri-rule-transfer"

    @property
    def mode(self) -> str:
        return "rule_based"

    def supports(self, source: str, target: str) -> bool:
        s = source.lower().split('_')[0]
        t = target.lower().split('_')[0]
        return (s == 'hin' and t == 'sck') or (s == 'sck' and t == 'hin')

    def translate_sentence(self, sent: str, source: str, target: str) -> str:
        s = source.lower().split('_')[0]
        t = target.lower().split('_')[0]

        if s == 'hin' and t == 'sck':
            return _RE_FORWARD.sub(lambda m: FORWARD_MAP[m.group(0)], sent)
        elif s == 'sck' and t == 'hin':
            return _RE_REVERSE.sub(lambda m: REVERSE_MAP[m.group(0)], sent)
        return sent

    def translate_sentences(self, sentences: List[str], source: str, target: str) -> List[str]:
        return [self.translate_sentence(s, source, target) for s in sentences]
