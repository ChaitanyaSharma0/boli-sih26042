FORWARD_MUNDARI_MAP = {k: v for k, v in MUNDARI_MAPPINGS}
_sorted_unr = sorted(FORWARD_MUNDARI_MAP.keys(), key=len, reverse=True)
_alts_unr = "|".join(re.escape(k) for k in _sorted_unr)
PUNCT = r"[^\s.,?!।॥\(\)\[\]\'\"]"
_RE_FORWARD_UNR = re.compile(rf"(?<!{PUNCT})(?:{_alts_unr})(?!{PUNCT})")

REVERSE_MUNDARI_MAP = {v: k for k, v in reversed(MUNDARI_MAPPINGS)}
_sorted_rev_unr = sorted(REVERSE_MUNDARI_MAP.keys(), key=len, reverse=True)
_alts_rev_unr = "|".join(re.escape(k) for k in _sorted_rev_unr)
_RE_REVERSE_UNR = re.compile(rf"(?<!{PUNCT})(?:{_alts_rev_unr})(?!{PUNCT})")


class MundariEngine(BaseTranslationEngine):
    @property
    def name(self) -> str:
        return "boli/mundari-linguistic-transfer"

    @property
    def mode(self) -> str:
        return "linguistic_transfer"

    def supports(self, source: str, target: str) -> bool:
        s = source.lower().split("_")[0]
        t = target.lower().split("_")[0]
        return (s == "hin" and t == "unr") or (s == "unr" and t == "hin")

    def translate_sentence(self, sent: str, source: str, target: str) -> str:
        s = source.lower().split("_")[0]
        t = target.lower().split("_")[0]
        if s == "hin" and t == "unr":
            return _RE_FORWARD_UNR.sub(lambda m: FORWARD_MUNDARI_MAP[m.group(0)], sent)
        elif s == "unr" and t == "hin":
            return _RE_REVERSE_UNR.sub(lambda m: REVERSE_MUNDARI_MAP[m.group(0)], sent)
        return sent

    def translate_sentences(self, sentences: List[str], source: str, target: str) -> List[str]:
        return [self.translate_sentence(s, source, target) for s in sentences]
